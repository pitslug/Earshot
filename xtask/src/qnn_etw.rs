/// Every Microsoft telemetry keyword, as one mask.
pub const TELEMETRY_MASK: u64 = 0x0000_E000_0000_0000;

/// ONNX Runtime's log provider (`ONNXRuntimeTraceLoggingProvider`).
pub const ORT_LOG_PROVIDER: &str = "{929DD115-1ECB-4CB5-B060-EBD4983C421D}";

/// The keyword mask to trace provider `guid` with: every keyword for ONNX Runtime's two
/// providers (telemetry and logging; the QNN plugin defines the telemetry one too), the
/// telemetry keywords for every other provider.
#[must_use]
pub fn trace_mask(guid: &str) -> u64 {
    if guid == ORT_PROVIDER || guid == ORT_LOG_PROVIDER {
        u64::MAX
    } else {
        TELEMETRY_MASK
    }
}

/// The provider GUIDs (upper case, with braces) in `logman query providers -pid` output.
#[must_use]
pub fn parse_providers(output: &str) -> Vec<String> {
    let mut out: Vec<String> = output
        .lines()
        .filter_map(|l| l.split_whitespace().last())
        .filter(|g| g.len() == 38 && g.starts_with('{') && g.ends_with('}'))
        .map(str::to_ascii_uppercase)
        .collect();
    out.sort();
    out.dedup();
    out
}

/// One decoded event, without its field values.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct EventShape {
    /// Provider name (as decoded) and GUID.
    pub provider: String,
    /// Keyword mask.
    pub keywords: u64,
    /// Level.
    pub level: u8,
    /// Event (task) name.
    pub name: String,
    /// Field names, in order.
    pub fields: Vec<String>,
}

impl EventShape {
    /// The Microsoft telemetry keywords it carries.
    #[must_use]
    pub fn telemetry(&self) -> Vec<&'static str> {
        TELEMETRY_KEYWORDS
            .iter()
            .filter(|(k, _)| self.keywords & k != 0)
            .map(|(_, n)| *n)
            .collect()
    }

    /// Whether this is ONNX Runtime's `ProcessInfo` telemetry event (the liveness signal).
    #[must_use]
    pub fn is_ort_process_info(&self) -> bool {
        self.provider.starts_with("Microsoft.ML.ONNXRuntime")
            && self.name == "ProcessInfo"
            && self.telemetry().contains(&"MEASURES")
    }
}

fn between<'a>(s: &'a str, start: &str, end: &str) -> Option<&'a str> {
    let i = s.find(start)? + start.len();
    let j = s[i..].find(end)?;
    Some(&s[i..i + j])
}

/// The event blocks of `tracerpt -of XML` output.
fn event_blocks(xml: &str) -> impl Iterator<Item = &str> {
    xml.split("<Event ")
        .skip(1)
        .map(|b| b.split("</Event>").next().unwrap_or(""))
}

fn block_pid(block: &str) -> Option<u32> {
    between(block, "ProcessID=\"", "\"").and_then(|p| p.parse().ok())
}

/// The provider ("Name {GUID}") of an event block.
fn block_provider(block: &str) -> String {
    let name = between(block, "<Provider Name=\"", "\"").unwrap_or("");
    let guid = between(block, "Guid=\"", "\"")
        .unwrap_or("")
        .to_ascii_uppercase();
    format!("{name} {guid}").trim().to_owned()
}

/// One run's decoded trace for the probe's process.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Decoded {
    /// Events by shape and count.
    pub events: BTreeMap<EventShape, usize>,
    /// `Data` elements whose name or value could not be read.
    pub unparsed: usize,
    /// Event counts of other processes on the traced providers, by provider.
    pub others: BTreeMap<String, usize>,
}

/// The events of process `pid` in `tracerpt -of XML` output, by shape and count, with the
/// `Data` elements that could not be parsed and other processes' events counted.
#[must_use]
pub fn decode(xml: &str, pid: u32) -> Decoded {
    let mut out = Decoded::default();
    for block in event_blocks(xml) {
        decode_block(&mut out, block, pid);
    }
    out
}

/// [`decode`] of one event block into `out`.
fn decode_block(out: &mut Decoded, block: &str, pid: u32) {
    let provider = block_provider(block);
    if block_pid(block) != Some(pid) {
        *out.others.entry(provider).or_insert(0) += 1;
        return;
    }
    {
        let keywords = between(block, "<Keywords>", "</Keywords>")
            .and_then(|k| u64::from_str_radix(k.trim().trim_start_matches("0x"), 16).ok())
            .unwrap_or(0);
        let level = between(block, "<Level>", "</Level>")
            .and_then(|l| l.trim().parse().ok())
            .unwrap_or(0);
        let task = between(block, "<RenderingInfo", "</RenderingInfo>")
            .and_then(|r| between(r, "<Task>", "</Task>"))
            .unwrap_or("")
            .to_owned();
        let mut fields = Vec::new();
        for d in block.split("<Data").skip(1) {
            match parse_data(d) {
                Some(name) => fields.push(name),
                None => out.unparsed += 1,
            }
        }
        let shape = EventShape {
            provider,
            keywords,
            level,
            name: task,
            fields,
        };
        *out.events.entry(shape).or_insert(0) += 1;
    }
}

/// The field name of one `<Data` element (`text` starts right after `<Data`): `Name="x">v</Data>`
/// or `Name="x" />`; `None` when it does not have that form.
fn parse_data(text: &str) -> Option<String> {
    let rest = text.strip_prefix(" Name=\"")?;
    let (name, rest) = rest.split_once('"')?;
    let rest = rest.trim_start();
    let ok = rest.starts_with("/>") || (rest.starts_with('>') && rest.contains("</Data>"));
    (ok && !name.is_empty()).then(|| name.to_owned())
}

/// The events of process `pid`, by shape and count (see [`decode`]).
#[must_use]
pub fn parse_events(xml: &str, pid: u32) -> BTreeMap<EventShape, usize> {
    decode(xml, pid).events
}

/// Why a telemetry-keyword event is not acceptable, `None` when it is a reviewed
/// system-information event with reviewed fields only.
#[must_use]
pub fn review(event: &EventShape) -> Option<String> {
    if event.telemetry().is_empty() {
        return None;
    }
    let provider = event.provider.split(" {").next().unwrap_or("");
    let Some((_, _, fields)) = SYSTEM_EVENTS
        .iter()
        .find(|(p, n, _)| *p == provider && *n == event.name)
    else {
        return Some("an unreviewed telemetry event".to_owned());
    };
    let unknown: Vec<&str> = event
        .fields
        .iter()
        .map(String::as_str)
        .filter(|f| !COMMON_FIELDS.contains(f) && !fields.contains(f))
        .collect();
    (!unknown.is_empty()).then(|| format!("unreviewed fields: {}", unknown.join(", ")))
}

fn unescape(s: &str) -> String {
    s.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}

fn hex_bytes(hex: &str) -> Option<Vec<u8>> {
    let hex: String = hex.chars().filter(|c| !c.is_whitespace()).collect();
    let hex = hex.strip_prefix("0x").unwrap_or(&hex);
    if !hex.len().is_multiple_of(2) {
        return None;
    }
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).ok())
        .collect()
}

/// Every text an event block carries, for the content check (never print it): attribute
/// values, every text node (`Data`, `UserData`, rendering info), and `Binary` payloads decoded
/// as UTF-8 and as UTF-16 LE.
#[must_use]
pub fn block_texts(block: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut in_tag = false;
    let mut text = String::new();
    let mut tag = String::new();
    for c in block.chars() {
        match c {
            '<' => {
                if !text.trim().is_empty() {
                    out.push(unescape(text.trim()));
                }
                text.clear();
                tag.clear();
                in_tag = true;
            }
            '>' if in_tag => {
                // Attribute values of the tag.
                for (i, part) in tag.split('"').enumerate() {
                    if i % 2 == 1 && !part.is_empty() {
                        out.push(unescape(part));
                    }
                }
                in_tag = false;
            }
            _ if in_tag => tag.push(c),
            _ => text.push(c),
        }
    }
    if !text.trim().is_empty() {
        out.push(unescape(text.trim()));
    }
    for b in block.split("<Binary>").skip(1) {
        if let Some(bytes) = b.split("</Binary>").next().and_then(hex_bytes) {
            out.push(String::from_utf8_lossy(&bytes).into_owned());
            let units: Vec<u16> = bytes
                .as_chunks::<2>()
                .0
                .iter()
                .map(|c| u16::from_le_bytes(*c))
                .collect();
            out.push(String::from_utf16_lossy(&units));
        }
    }
    out
}

/// The words of `text` that identify it: five letters or more, lower case.
#[must_use]
pub fn content_needles(text: &str) -> Vec<String> {
    let mut words: Vec<String> = text
        .split(|c: char| !c.is_alphanumeric() && c != '\'')
        .filter(|w| w.chars().filter(|c| c.is_alphabetic()).count() >= 5)
        .map(str::to_lowercase)
        .collect();
    words.sort();
    words.dedup();
    words
}

/// The providers of the events of process `pid` whose text holds any of `needles`
/// (case-insensitive), and how many texts were searched.
#[must_use]
pub fn content_hits(xml: &str, pid: u32, needles: &[String]) -> (Vec<String>, usize) {
    let mut hits = Vec::new();
    let mut searched = 0;
    for block in event_blocks(xml) {
        content_block(block, pid, needles, &mut hits, &mut searched);
    }
    hits.sort();
    hits.dedup();
    (hits, searched)
}

/// [`content_hits`] of one event block.
fn content_block(
    block: &str,
    pid: u32,
    needles: &[String],
    hits: &mut Vec<String>,
    searched: &mut usize,
) {
    if block_pid(block) != Some(pid) {
        return;
    }
    let texts = block_texts(block);
    *searched += texts.len();
    let found = texts.iter().any(|t| {
        let t = t.to_lowercase();
        needles.iter().any(|n| t.contains(n.as_str()))
    });
    if found {
        hits.push(block_provider(block));
    }
}

/// One `tracerpt -of XML` file scanned for process `pid`: [`decode`] and [`content_hits`]
/// together, read line by line so a multi-gigabyte trace (other processes on the traced
/// providers during an 8-minute run) never has to fit in memory.
#[derive(Debug, Default)]
pub struct Scan {
    /// The decoded events.
    pub decoded: Decoded,
    /// Providers of events whose text holds conversation content.
    pub content: Vec<String>,
    /// Texts searched.
    pub searched: usize,
    /// Whether the file ended with `</Events>` (not cut short).
    pub complete: bool,
}

/// Scans the XML text read from `reader` (see [`Scan`]).
///
/// # Errors
/// A read error.
pub fn scan_xml(reader: impl BufRead, pid: u32, needles: &[String]) -> Result<Scan> {
    let mut scan = Scan::default();
    let mut block: Option<String> = None;
    let mut last = String::new();
    let mut reader = reader;
    let mut line = Vec::new();
    loop {
        line.clear();
        if reader.read_until(b'\n', &mut line)? == 0 {
            break;
        }
        let text = String::from_utf8_lossy(&line);
        if !text.trim().is_empty() {
            last = text.trim().to_owned();
        }
        let mut rest: &str = &text;
        loop {
            match block.as_mut() {
                None => match rest.find("<Event ") {
                    Some(i) => {
                        block = Some(String::new());
                        rest = &rest[i + "<Event ".len()..];
                    }
                    None => break,
                },
                Some(b) => match rest.find("</Event>") {
                    Some(i) => {
                        b.push_str(&rest[..i]);
                        decode_block(&mut scan.decoded, b, pid);
                        content_block(b, pid, needles, &mut scan.content, &mut scan.searched);
                        block = None;
                        rest = &rest[i + "</Event>".len()..];
                    }
                    None => {
                        b.push_str(rest);
                        break;
                    }
                },
            }
        }
    }
    scan.complete = block.is_none() && last.ends_with("</Events>");
    scan.content.sort();
    scan.content.dedup();
    Ok(scan)
}

/// One traced run, as [`verdict`] judges it.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct RunReport {
    /// What ran.
    pub title: String,
    /// Whether every captured output it was parsed from (probe stdout, `tracerpt`) was complete.
    pub complete: bool,
    /// The probe process's trace.
    pub decoded: Decoded,
    /// Providers of events whose text holds conversation content.
    pub content: Vec<String>,
}

/// Every reason the check fails (empty: it passes). Fails closed: an incomplete output, an
/// empty trace or a trace without ONNX Runtime's `ProcessInfo` fails, as does any unreviewed
/// telemetry event or field, any unparsed `Data` element and any conversation content.
#[must_use]
pub fn verdict(runs: &[RunReport]) -> Vec<String> {
    let mut why = Vec::new();
    if runs.is_empty() {
        why.push("no run was traced".to_owned());
    }
    for r in runs {
        let t = &r.title;
        if !r.complete {
            why.push(format!("{t}: incomplete output"));
        }
        if r.decoded.events.is_empty() {
            why.push(format!("{t}: no event of the probe's process was traced"));
        }
        if !r.decoded.events.keys().any(EventShape::is_ort_process_info) {
            why.push(format!(
                "{t}: ONNX Runtime's ProcessInfo MEASURES event is missing (the trace missed the telemetry channel)"
            ));
        }
        if r.decoded.unparsed > 0 {
            why.push(format!(
                "{t}: {} Data element(s) could not be parsed",
                r.decoded.unparsed
            ));
        }
        for (e, n) in &r.decoded.events {
            if let Some(reason) = review(e) {
                why.push(format!(
                    "{t}: NOT ALLOWED ({reason}): {n} x {} event {:?} ({}) fields [{}]",
                    e.provider,
                    e.name,
                    e.telemetry().join(", "),
                    e.fields.join(", ")
                ));
            }
        }
        if !r.content.is_empty() {
            why.push(format!(
                "{t}: CONTENT FOUND in events of {} (values not printed)",
                r.content.join(", ")
            ));
        }
    }
    why
}

/// Runs `cmd` under `timeout`; its complete stdout, or an error.
fn run_ok(cmd: &mut Command, what: &str, timeout: Duration) -> Result<String> {
    let done = run_with_timeout(cmd, timeout)
        .with_context(|| format!("{what} did not finish within the deadline"))?;
    ensure!(done.success, "{what} failed: {}", done.describe());
    done.require_complete(what)?;
    Ok(done.stdout)
}

/// Starts the probe in `mode`, waits for its `ready <pid>` line, lists the providers its
/// process registered and lets it exit.
fn providers_of(exe: &Path, models: &Path, mode: &str, clip: &Path) -> Result<Vec<String>> {
    let mut child = Command::new(exe)
        .arg(models)
        .arg("30")
        .arg(mode)
        .arg(clip)
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()
        .with_context(|| format!("start {}", exe.display()))?;
    let stdout = child.stdout.take().context("probe stdout")?;
    let (tx, rx) = mpsc::channel();
    std::thread::spawn(move || {
        for line in BufReader::new(stdout).lines().map_while(Result::ok) {
            if line.starts_with("ready ") {
                let _ = tx.send(());
            }
        }
    });
    let ready = rx.recv_timeout(READY_TIMEOUT);
    // `logman query providers -pid` sometimes fails with "The GUID passed was not recognized"
    // and its lists differed between queries (25 and 62 providers on two runs): up to eight
    // queries a second apart, the union of three successful ones.
    let listed: Option<Result<Vec<String>>> = ready.is_ok().then(|| {
        let mut union: Vec<String> = Vec::new();
        let (mut ok, mut last) = (0, None);
        for _ in 0..8 {
            std::thread::sleep(Duration::from_secs(1));
            match run_ok(
                Command::new("logman")
                    .args(["query", "providers", "-pid"])
                    .arg(child.id().to_string()),
                "logman query providers",
                STEP_TIMEOUT,
            ) {
                Ok(out) => {
                    union.extend(parse_providers(&out));
                    ok += 1;
                    if ok == 3 {
                        break;
                    }
                }
                Err(e) => last = Some(e),
            }
        }
        if ok == 0 {
            return Err(last.unwrap_or_else(|| anyhow::anyhow!("logman query providers failed")));
        }
        union.sort();
        union.dedup();
        Ok(union)
    });
    let _ = child.kill();
    let _ = child.wait();
    ensure!(ready.is_ok(), "qnn_etw_probe ({mode}) never got ready");
    let providers = listed.context("no provider list")??;
    ensure!(
        !providers.is_empty(),
        "logman listed no provider for the probe"
    );
    Ok(providers)
}

/// A traced probe run: its pid, the decoded XML and the probe's stdout.
struct Traced {
    pid: u32,
    xml: PathBuf,
    stdout: String,
}

/// Traces one probe run with `args` after the mode.
fn trace(
    exe: &Path,
    models: &Path,
    mode: &str,
    args: &[std::ffi::OsString],
    dir: &Path,
    providers: &Path,
) -> Result<Traced> {
    let etl = dir.join(format!("{mode}.etl"));
    let xml = dir.join(format!("{mode}.xml"));
    let _ = std::fs::remove_file(&etl);
    let _ = std::fs::remove_file(&xml);
    // A session left over from an interrupted run.
    let _ = run_with_timeout(
        Command::new("logman").args(["stop", SESSION, "-ets"]),
        STEP_TIMEOUT,
    );
    run_ok(
        Command::new("logman")
            .args(["create", "trace", SESSION, "-ets", "-o"])
            .arg(&etl)
            .arg("-pf")
            .arg(providers),
        "logman create trace (needs an administrator or a member of Performance Log Users)",
        STEP_TIMEOUT,
    )?;
    let mut cmd = Command::new(exe);
    cmd.arg(models).arg("1").arg(mode).args(args);
    let probe = run_with_timeout(&mut cmd, PROBE_TIMEOUT);
    // `logman stop` sometimes fails with "The GUID passed was not recognized" and leaves the
    // session running; a later try stops it (seen 2026-10-24 after the QNN run).
    let mut stopped = Err(anyhow::anyhow!("logman stop was not run"));
    for _ in 0..5 {
        stopped = run_ok(
            Command::new("logman").args(["stop", SESSION, "-ets"]),
            "logman stop",
            STEP_TIMEOUT,
        );
        if stopped.is_ok() {
            break;
        }
        std::thread::sleep(Duration::from_secs(1));
    }
    stopped?;
    let probe = probe.context("qnn_etw_probe did not finish within the deadline")?;
    ensure!(
        probe.success,
        "qnn_etw_probe ({mode}) failed: {}",
        probe.describe()
    );
    probe.require_complete("qnn_etw_probe")?;
    let pid = probe
        .stdout
        .lines()
        .find_map(|l| l.strip_prefix("ready ")?.trim().parse::<u32>().ok())
        .context("qnn_etw_probe printed no pid")?;
    for l in probe.stdout.lines().filter(|l| !l.starts_with("ready ")) {
        eprintln!("qnn-etw: {l}");
    }
    run_ok(
        Command::new("tracerpt")
            .arg(&etl)
            .arg("-o")
            .arg(&xml)
            .args(["-of", "XML", "-y"]),
        "tracerpt",
        PROBE_TIMEOUT,
    )?;
    Ok(Traced {
        pid,
        xml,
        stdout: probe.stdout,
    })
}

fn print_events(title: &str, d: &Decoded) {
    println!(
        "qnn-etw: {title}: {} event(s)",
        d.events.values().sum::<usize>()
    );
    for (e, n) in &d.events {
        let telemetry = e.telemetry();
        println!(
            "  {n:4}  {}  keywords 0x{:x}{}  level {}  event {:?}  fields [{}]",
            e.provider,
            e.keywords,
            if telemetry.is_empty() {
                String::new()
            } else {
                format!(" ({})", telemetry.join(", "))
            },
            e.level,
            e.name,
            e.fields.join(", ")
        );
    }
    if !d.others.is_empty() {
        let others: Vec<String> = d.others.iter().map(|(p, n)| format!("{p} x{n}")).collect();
        println!(
            "  (informational) other processes on the traced providers during the run: {}",
            others.join("; ")
        );
    }
}

/// Runs the check (module docs). Returns whether it passed.
///
/// # Errors
/// A failed build, probe, `logman` or `tracerpt` step.
pub fn run(root: &Path) -> Result<bool> {
    let models = crate::models::cache_dir()?;
    let dir: PathBuf = root.join("target").join("qnn-etw");
    std::fs::create_dir_all(&dir).with_context(|| format!("create {}", dir.display()))?;
    let mut build = cargo_command();
    build
        .args([
            "build",
            "--release",
            "-p",
            "earshot-onnx",
            "--features",
            "qnn",
            "--example",
            "qnn_etw_probe",
            "--message-format=json-render-diagnostics",
        ])
        .current_dir(root);
    eprintln!("qnn-etw: building qnn_etw_probe (release, qnn)");
    let built = run_with_timeout(&mut build, BUILD_TIMEOUT)
        .context("building qnn_etw_probe did not finish within the deadline")?;
    if !built.success {
        bail!("building qnn_etw_probe failed: {}", built.describe());
    }
    built.require_complete("building qnn_etw_probe")?;
    let exe = crate::qnn_convert::example_executable(&built.stdout, "qnn_etw_probe")
        .context("cargo reported no qnn_etw_probe executable")?;

    let clip = root.join("fixtures/smoke").join(format!("{CLIP_ID}.flac"));
    let reference = std::fs::read_to_string(root.join("fixtures/smoke/transcripts.txt"))?
        .lines()
        .find_map(|l| l.strip_prefix(CLIP_ID).map(str::trim).map(str::to_owned))
        .context("no smoke transcript for the clip")?;

    // Every provider the QNN process registers, plus ONNX Runtime's.
    let mut traced = providers_of(&exe, &models, "qnn", &clip)?;
    traced.push(ORT_PROVIDER.to_owned());
    traced.push(ORT_LOG_PROVIDER.to_owned());
    traced.sort();
    traced.dedup();
    println!(
        "qnn-etw: tracing all {} providers the QNN process registers plus ONNX Runtime's (ONNX Runtime's with every keyword, the rest with the telemetry keywords)",
        traced.len()
    );
    let providers = dir.join("providers.txt");
    let list: String = traced
        .iter()
        .map(|g| format!("{g} 0x{:x} 0xff\r\n", trace_mask(g)))
        .collect();
    std::fs::write(&providers, list)?;

    let clip_arg = || clip.clone().into_os_string();
    let cpu = trace(&exe, &models, "cpu", &[clip_arg()], &dir, &providers)?;
    let qnn = trace(&exe, &models, "qnn", &[clip_arg()], &dir, &providers)?;
    let heard_file = dir.join("heard.txt");
    let _ = std::fs::remove_file(&heard_file);
    let talk = trace(
        &exe,
        &models,
        "transcribe",
        &[clip_arg(), heard_file.clone().into_os_string()],
        &dir,
        &providers,
    )?;
    let heard = std::fs::read_to_string(&heard_file).context("the probe wrote no transcript")?;
    let _ = std::fs::remove_file(&heard_file);
    let on_npu = talk
        .stdout
        .lines()
        .any(|l| l.starts_with("transcribe-backend qnn"));

    let mut needles = content_needles(&reference);
    needles.extend(content_needles(&heard));
    needles.push(CLIP_ID.to_lowercase());
    needles.sort();
    needles.dedup();

    let mut runs = Vec::new();
    let mut searched = 0;
    for (title, t) in [
        ("baseline (CPU EP, no plugin)", &cpu),
        ("with the QNN plugin", &qnn),
        (
            if on_npu {
                "with the QNN plugin, transcribing the clip on the QNN EP"
            } else {
                "with the QNN plugin, transcribing the clip on the CPU EP"
            },
            &talk,
        ),
    ] {
        let file =
            std::fs::File::open(&t.xml).with_context(|| format!("open {}", t.xml.display()))?;
        let scan = scan_xml(BufReader::new(file), t.pid, &needles)?;
        print_events(title, &scan.decoded);
        searched += scan.searched;
        runs.push(RunReport {
            title: title.to_owned(),
            complete: scan.complete,
            decoded: scan.decoded,
            content: scan.content,
        });
    }
    println!(
        "qnn-etw: content check: {searched} text(s) of the probe's events searched for {} words of the clip's transcript and its name (never printed)",
        needles.len()
    );
    let why = verdict(&runs);
    if why.is_empty() {
        // The traces can be gigabytes; they are kept only when the check fails.
        for t in [&cpu, &qnn, &talk] {
            let _ = std::fs::remove_file(&t.xml);
            let _ = std::fs::remove_file(t.xml.with_extension("etl"));
        }
        if on_npu {
            println!(
                "qnn-etw: PASS: only reviewed system information is offered to telemetry, and no conversation content (the clip was transcribed on the QNN EP)"
            );
        } else {
            println!(
                "qnn-etw: PASS (qualified): only reviewed system information is offered to telemetry, and no conversation content; the clip was transcribed on the CPU EP on this host (no NPU conversion installed), the QNN EP ran the VAD over the clip"
            );
        }
        Ok(true)
    } else {
        println!("qnn-etw: FAIL:");
        for w in &why {
            println!("  {w}");
        }
        Ok(false)
    }
}

