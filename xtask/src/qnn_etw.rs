//! `cargo xtask qnn-etw` (T8.3): what ONNX Runtime, Qualcomm's QNN plugin
//! and the Windows components they load offer to Windows' event tracing (ETW), the channel
//! Windows telemetry (TraceLogging, collected by the Connected User Experiences service)
//! travels on. Nothing is installed: Windows' own `logman` and `tracerpt` record and decode the
//! trace; the user must be an administrator or in "Performance Log Users".
//!
//! 1. Builds the `qnn_etw_probe` example of `earshot-onnx` (release, `qnn`): ONNX Runtime with
//!    telemetry off, the QNN plugin registered through `register_qnn`, Silero VAD run on the QNN
//!    EP over the frames of a real smoke clip (the HTP simulator on x64, the NPU on ARM64).
//!    Mode `cpu` is the baseline: the same work on the CPU EP without the plugin.
//! 2. Lists every ETW provider the QNN run registers in its process (`logman query providers
//!    -pid`) and traces all of them, plus ONNX Runtime's own (`Microsoft.ML.ONNXRuntime`), at
//!    every level ([`trace_mask`]): ONNX Runtime's two providers with every keyword, all the
//!    others with the three telemetry keywords (the only events Windows telemetry collects;
//!    events without a keyword are delivered too). With every keyword, the machine-wide
//!    diagnostics of Windows providers made a 1-5 GB trace in an 8-minute run.
//! 3. Traces three runs (`logman create trace -ets`): the baseline, the QNN run, and a QNN run
//!    that also transcribes the clip (`transcribe`): on the QNN EP with the NPU conversion of
//!    Parakeet TDT 110M when it is installed, else on the CPU EP (the verdict then says so).
//!    Decodes them (`tracerpt -of XML`) and reports, for the probe's process, every event by
//!    provider, keywords, level, event name and *field names* (never values); events of other
//!    processes on the traced providers are counted in an informational line.
//!
//! Verdict: system information may be offered to Windows
//! telemetry, conversation content (audio, transcript text, summaries, speaker, file or
//! meeting names, prompts) never. [`verdict`] fails closed: it passes only when
//! - every run's captured output was complete and its trace holds events of the probe's
//!   process, including ONNX Runtime's `ProcessInfo` MEASURES event (the known liveness
//!   signal: a trace that missed it missed the telemetry channel);
//! - every event with a Microsoft telemetry keyword (`MEASURES`, `TELEMETRY`,
//!   `CRITICAL_DATA`), whoever sends it, is a reviewed system-information event with only
//!   reviewed fields ([`SYSTEM_EVENTS`]); an unknown event or field fails (it needs review);
//! - every `Data` element was parsed; and
//! - no text of any event of the probe's process (every text node, and `Binary` payloads
//!   decoded as UTF-8 and UTF-16) contains the clip's transcript (any word of five letters or
//!   more, of the reference or of what was heard) or the clip's name. Text is compared in
//!   memory and never printed.

