//! Suggestions beside words (T12.15e): a decoded word that sounds like exactly one listed
//! word is offered that word, and nothing changes until the user accepts it.
//!
//! This is T12.15ea's `sound-rare` matcher (docs/vocabulary.md, "Suggestions on meeting
//! speech (T12.15ea)": 5 suggestions in 1.61 meeting hours on AMI dev, all right), moved
//! unchanged from the `vocab_eval` example, which now calls it. For every white-space token of
//! a segment's text:
//!
//! 1. its core is the token from its first to its last letter, digit or apostrophe
//!    ([`split_punctuation`]); a token with no core is skipped;
//! 2. a core equal to a listed word in any case is skipped (it already reads as listed);
//! 3. a core whose [`sound_key`] is shorter than two letters is skipped (too short to say
//!    anything about its sound);
//! 4. a core that is a common word ([`is_common`]: every normalised token of it is one of the
//!    5,000 most frequent AMI tokens of `data/common_words.txt`) is skipped;
//! 5. the listed words with the same sound key are its candidates; exactly one candidate is a
//!    suggestion, none or several is nothing.
//!
//! The common words are generated by `cargo xtask common-words` from the pinned AMI manual
//! annotations (CC BY 4.0, `data/common_words.txt.NOTICE`).

use std::collections::HashSet;
use std::sync::OnceLock;

use crate::metrics::normalize::normalize_english;

/// How many common words `data/common_words.txt` holds.
pub const COMMON_WORDS: usize = 5_000;

/// One suggestion: which white-space token of the text, the token as decoded (punctuation
/// kept) and the one listed word it sounds like (as listed).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Suggestion {
    /// Index of the token among the text's white-space tokens.
    pub token: usize,
    /// The token as written in the text.
    pub decoded: String,
    /// The listed word offered in its place.
    pub listed: String,
}

/// `data/common_words.txt`: one token per line, most frequent first.
const COMMON_WORDS_TXT: &str = include_str!("data/common_words.txt");

static COMMON: OnceLock<HashSet<&'static str>> = OnceLock::new();

/// The common words (see the module doc).
pub fn common_words() -> &'static HashSet<&'static str> {
    COMMON.get_or_init(|| COMMON_WORDS_TXT.lines().collect())
}

/// Whether every normalised token of `word` (the WER normaliser, split on white space) is a
/// common word, and it has one.
#[must_use]
pub fn is_common(word: &str) -> bool {
    let normalised = normalize_english(word);
    let mut tokens = normalised.split_whitespace().peekable();
    let common = common_words();
    tokens.peek().is_some() && tokens.all(|t| common.contains(t))
}

/// The reduced sound key of docs/vocabulary.md (after Philips' Metaphone, 1990): ASCII
/// letters only, lower case; `kn`/`wr`/`gh` at the start lose their first letter; `sch` ->
/// `sk`, `ph` -> `f`, `ck` -> `k`, `qu` -> `kw`, `wh` -> `w`, `gh` dropped; `c` is `s` before
/// `e`/`i`/`y` and `k` elsewhere, `q` -> `k`, `x` -> `ks`, `z` -> `s`, `v` -> `f`; a leading
/// vowel (or `y`) is `a`, later vowels, `y`, `h` and `w` are dropped; repeated letters
/// collapse.
#[must_use]
pub fn sound_key(word: &str) -> String {
    let mut s: String = word
        .chars()
        .flat_map(char::to_lowercase)
        .filter(char::is_ascii_lowercase)
        .collect();
    for (from, to) in [("kn", "n"), ("wr", "r"), ("gh", "g")] {
        if let Some(rest) = s.strip_prefix(from) {
            s = format!("{to}{rest}");
        }
    }
    for (from, to) in [
        ("sch", "sk"),
        ("ph", "f"),
        ("ck", "k"),
        ("qu", "kw"),
        ("wh", "w"),
        ("gh", ""),
    ] {
        s = s.replace(from, to);
    }
    let chars: Vec<char> = s.chars().collect();
    let mut mapped = String::new();
    for (i, &c) in chars.iter().enumerate() {
        match c {
            'c' => {
                let soft = matches!(chars.get(i + 1), Some('e' | 'i' | 'y'));
                mapped.push(if soft { 's' } else { 'k' });
            }
            'q' => mapped.push('k'),
            'x' => mapped.push_str("ks"),
            'z' => mapped.push('s'),
            'v' => mapped.push('f'),
            _ => mapped.push(c),
        }
    }
    let mut key = String::new();
    for (i, c) in mapped.chars().enumerate() {
        let c = if i == 0 {
            if matches!(c, 'a' | 'e' | 'i' | 'o' | 'u' | 'y') {
                'a'
            } else {
                c
            }
        } else if matches!(c, 'a' | 'e' | 'i' | 'o' | 'u' | 'y' | 'h' | 'w') {
            continue;
        } else {
            c
        };
        if !key.ends_with(c) {
            key.push(c);
        }
    }
    key
}

/// `word` split into leading punctuation, its core (from the first to the last letter, digit
/// or apostrophe) and trailing punctuation. A word with no core is all leading punctuation.
#[must_use]
pub fn split_punctuation(word: &str) -> (&str, &str, &str) {
    let keep = |c: char| c.is_alphanumeric() || c == '\'';
    let Some(start) = word.find(keep) else {
        return (word, "", "");
    };
    let end = word.rfind(keep).map_or(word.len(), |i| {
        i + word[i..].chars().next().map_or(1, char::len_utf8)
    });
    (&word[..start], &word[start..end], &word[end..])
}

/// One listed word as the matcher compares it.
#[derive(Debug, Clone)]
struct Listed {
    form: String,
    lower: String,
    key: String,
}

/// A word list ready to match decoded text against (the steps of the module doc).
#[derive(Debug, Clone)]
pub struct Suggester {
    listed: Vec<Listed>,
}

impl Suggester {
    /// A suggester for `listed`, in list order. A word listed twice has two candidates of
    /// one sound, so it is never suggested (step 5).
    #[must_use]
    pub fn new<S: AsRef<str>>(listed: &[S]) -> Self {
        Suggester {
            listed: listed
                .iter()
                .map(|f| {
                    let form = f.as_ref();
                    Listed {
                        form: form.to_owned(),
                        lower: form.to_lowercase(),
                        key: sound_key(form),
                    }
                })
                .collect(),
        }
    }

    /// The one listed word the decoded `word` (one token, punctuation kept) sounds like, if
    /// any.
    #[must_use]
    pub fn suggest_word(&self, word: &str) -> Option<&str> {
        let (_, core, _) = split_punctuation(word);
        let lower = core.to_lowercase();
        if core.is_empty() || self.listed.iter().any(|l| l.lower == lower) {
            return None;
        }
        let key = sound_key(core);
        if key.chars().count() < 2 || is_common(core) {
            return None;
        }
        let mut candidates = self.listed.iter().filter(|l| l.key == key);
        match (candidates.next(), candidates.next()) {
            (Some(only), None) => Some(only.form.as_str()),
            _ => None,
        }
    }

    /// Every suggestion for `text`, in token order; tokens are the text's white-space tokens.
    #[must_use]
    pub fn suggest(&self, text: &str) -> Vec<Suggestion> {
        text.split_whitespace()
            .enumerate()
            .filter_map(|(token, word)| {
                self.suggest_word(word).map(|listed| Suggestion {
                    token,
                    decoded: word.to_owned(),
                    listed: listed.to_owned(),
                })
            })
            .collect()
    }
}

/// Every suggestion for `text` against `listed`, in token order.
#[must_use]
pub fn suggest<S: AsRef<str>>(text: &str, listed: &[S]) -> Vec<Suggestion> {
    Suggester::new(listed).suggest(text)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sg(token: usize, decoded: &str, listed: &str) -> Suggestion {
        Suggestion {
            token,
            decoded: decoded.to_owned(),
            listed: listed.to_owned(),
        }
    }

    #[test]
    fn vocabulary_suggest_common_words_are_the_embedded_list() {
        let raw = include_str!("data/common_words.txt");
        assert!(!raw.contains('\r') && raw.ends_with('\n'));
        assert_eq!(raw.lines().count(), COMMON_WORDS);
        assert_eq!(common_words().len(), COMMON_WORDS);
        assert_eq!(raw.lines().next(), Some("the"));
        assert!(is_common("The"));
        assert!(is_common("come,"));
        assert!(!is_common("Bozzle"));
        assert!(!is_common(""));
        assert!(!is_common("--"));
    }

    #[test]
    fn vocabulary_suggest_sound_keys_join_spellings_of_one_sound() {
        assert_eq!(sound_key("Kam"), sound_key("Cam"));
        assert_eq!(sound_key("Kat"), sound_key("cat"));
        assert_eq!(sound_key("Stephen"), sound_key("Steven"));
        assert_eq!(sound_key("Philips"), sound_key("Filips"));
        assert_eq!(sound_key("Knight"), "nt");
        // Letters that meet once the vowels are gone collapse too.
        assert_eq!(sound_key("Cecil"), "sl");
        assert_eq!(sound_key("Xavier"), "ksfr");
        assert_eq!(sound_key("Ollie"), "al");
        assert_eq!(sound_key("Bozle"), sound_key("Bozzle"));
        assert_ne!(sound_key("Kam"), sound_key("Pam"));
        // The cost the doc names: a common word can share a name's key.
        assert_eq!(sound_key("come"), sound_key("Kam"));
    }

    #[test]
    fn vocabulary_suggest_punctuation_is_split_off() {
        assert_eq!(split_punctuation("\"Cam,"), ("\"", "Cam", ","));
        assert_eq!(split_punctuation("don't."), ("", "don't", "."));
        assert_eq!(split_punctuation("--"), ("--", "", ""));
        assert_eq!(split_punctuation("café!"), ("", "café", "!"));
    }

    #[test]
    fn vocabulary_suggest_offers_one_listed_word_and_never_touches_common_words() {
        let listed = ["Kam", "Kat", "Bozzle"];
        let got = suggest("Cam, will come the cat Bozle Kam", &listed);
        // "come" and "cat" share a listed word's sound but are common; "Kam" is listed.
        assert_eq!(got, [sg(0, "Cam,", "Kam"), sg(5, "Bozle", "Bozzle")]);
    }

    #[test]
    fn vocabulary_suggest_skips_listed_words_in_any_case() {
        assert!(suggest("KAM. kam \"Kam\"", &["Kam"]).is_empty());
        assert!(suggest("bozzle", &["BOZZLE"]).is_empty());
    }

    #[test]
    fn vocabulary_suggest_leaves_ambiguous_short_and_wordless_tokens() {
        // Two listed words with the decoded word's sound: nothing.
        assert!(suggest("Cam", &["Kam", "Cahm"]).is_empty());
        // A sound key of one letter says nothing.
        assert!(suggest("Eh", &["Ah"]).is_empty());
        assert!(suggest("-- ... !", &["Kam"]).is_empty());
        assert!(suggest("", &["Kam"]).is_empty());
        assert!(suggest("Cam", &[] as &[&str]).is_empty());
    }

    #[test]
    fn vocabulary_suggest_counts_white_space_tokens() {
        let got = suggest("  so   (Cam)\tsaid\nBozle! ", &["Kam", "Bozzle"]);
        assert_eq!(got, [sg(1, "(Cam)", "Kam"), sg(3, "Bozle!", "Bozzle")]);
        // The text, the token and the word agree.
        let s = Suggester::new(&["Kam", "Bozzle"]);
        for g in &got {
            assert_eq!(
                "  so   (Cam)\tsaid\nBozle! "
                    .split_whitespace()
                    .nth(g.token),
                Some(g.decoded.as_str())
            );
            assert_eq!(s.suggest_word(&g.decoded), Some(g.listed.as_str()));
        }
        assert_eq!(s.suggest_word("said"), None);
    }
}
